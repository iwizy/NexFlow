#!/usr/bin/env node
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { assertDecisionBundle, verifyDecisionBundle, verifyDraftText, rfcPath } from "./lib/runtime-decision-bundle.mjs";

const bundle = verifyDecisionBundle();
assert.equal(bundle.rfc.status, "Draft");
assert.equal(bundle.rfc.revision, null);
assert.equal(bundle.outcome, "not-ready");
assert.equal(bundle.runtimeImplementationAuthorized, false);
assert.equal(bundle.evidenceIndex.length, 33);
assert.equal(bundle.prerequisites.successfulChecks, 20);
assert.equal(bundle.gates.length, 11);
assert.ok(bundle.gates.every(g => g.status === "blocked" && g.closed === false && g.evidence.length > 1 && g.blockers.length > 0));
assert.equal(bundle.candidates.length, 4);
assert.ok(bundle.candidates.every(c => c.schemaValid && c.assessment.outcome === "ineligible" && c.hardGates.specificationFidelity.status === "failed" && c.fidelity["not-tested"] === 224));
assert.equal(bundle.candidates.reduce((sum, c) => sum + c.missingComparableMetricCells, 0), 84);
assert.ok(bundle.candidates.every(c => c.advisoryRefreshed === false));
assert.equal(bundle.targetMatrix.length, 3);
assert.equal(bundle.targetMatrix.reduce((sum, t) => sum + t.candidateObservations.length, 0), 12);
assert.ok(bundle.targetMatrix.every(t => t.productSupport === "not-declared" && t.candidateObservations.every(c => c.comparableMetricSamples === 0 && c.stages.upgrade === "not-tested" && c.stages.rollback === "not-tested" && c.stages.signing === "not-tested")));
assert.ok(bundle.targetMatrix.every(t => t.candidateObservations.find(c => c.candidate === "rust").stages.validateInspect === "failed"));
const windows = bundle.targetMatrix.find(t => t.target === "windows/amd64");
assert.equal(windows.candidateObservations.find(c => c.candidate === "python").stages.build, "failed");
assert.equal(windows.candidateObservations.find(c => c.candidate === "python").artifactSha256, null);
assert.ok(windows.candidateObservations.filter(c => c.candidate !== "python").every(c => c.stages.install === "failed"));
assert.equal(bundle.alternatives.length, 3);
assert.ok(bundle.alternatives.every(v => v.status === "unselected"));
assert.equal(bundle.versionDomains.length, 9);
assert.equal(bundle.ownershipProposals.length, 6);
assert.equal(bundle.reviewerProposals.length, 2);
assert.ok(bundle.ownershipProposals.every(v => v.status === "pending" && v.confirmedOwner === null));
assert.ok(bundle.humanDecisions.every(v => v.status === "pending" && v.consent === null && v.decision === null));
assert.deepEqual(bundle.review.reviewers, []);
assert.equal(bundle.review.completedScores, null);
assert.equal(bundle.review.reconciliation, null);
assert.deepEqual(bundle.review.signatures, []);
assert.equal(bundle.acceptance.authorized, false);

let controls = 0;
const reject = mutate => {
  const changed = structuredClone(bundle); mutate(changed);
  assert.throws(() => assertDecisionBundle(changed, bundle)); controls++;
};
reject(b => { b.rfc.status = "Accepted"; });
reject(b => { b.rfc.revision = "a".repeat(40); });
reject(b => { b.rfc.sha256 = "a".repeat(64); });
reject(b => { b.outcome = "accepted"; });
reject(b => { b.selectedCandidate = "typescript"; });
reject(b => { b.selectedLayout = "shared-packages"; });
reject(b => { b.runtimeImplementationAuthorized = true; });
reject(b => { b.productSupportTargets = ["macos/arm64"]; });
reject(b => { b.specificationRevision = "a".repeat(40); });
reject(b => { b.evidenceIndex.pop(); });
reject(b => { b.evidenceIndex[0].revision = "main"; });
reject(b => { b.prerequisites.successfulChecks = 21; });
reject(b => { b.gates.pop(); });
reject(b => { b.gates[0].status = "passed"; });
reject(b => { b.gates[0].closed = true; });
reject(b => { b.gates[0].blockers = []; });
reject(b => { b.gates[0].evidence = []; });
reject(b => { b.candidates[0].assessment.outcome = "candidate-evidence-complete"; });
reject(b => { b.candidates[0].hardGates.specificationFidelity.status = "passed"; });
reject(b => { b.candidates[0].missingComparableMetricCells = 0; });
reject(b => { b.candidates[0].advisoryRefreshed = true; });
reject(b => { b.targetMatrix[0].contract.snapshot.imageVersion = "changed"; });
reject(b => { b.targetMatrix[0].candidateObservations[0].frozenCheck.matched = true; });
reject(b => { b.targetMatrix[0].candidateObservations[2].stages.validateInspect = "passed"; });
reject(b => { b.targetMatrix[2].candidateObservations[1].artifactSha256 = "a".repeat(64); });
reject(b => { b.targetMatrix[0].candidateObservations[0].comparableMetricSamples = 1; });
reject(b => { b.ownershipProposals[0].confirmedOwner = "unconfirmed"; });
reject(b => { b.humanDecisions[0].consent = true; });
reject(b => { b.review.reviewers = ["unconfirmed", "same"]; });
reject(b => { b.review.completedScores = [5, 5]; });
reject(b => { b.review.reconciliation = "unconfirmed"; });
reject(b => { b.review.signatures = ["unconfirmed"]; });
reject(b => { b.acceptance.authorized = true; });
reject(b => { b.alternatives.pop(); });
const text = readFileSync(rfcPath, "utf8"), titles = bundle.gates.map(g => g.title);
for (const invalid of [text.replace("## Status\n\nDraft", "## Status\n\nAccepted"), text.replace("| 11 Rationale, Governance, And Ownership |", "| 12 Rationale, Governance, And Ownership |"), text.replace("`signing`", "signing-omitted"), text.replace("selectedCandidate = null", "selectedCandidate = typescript")]) {
  assert.throws(() => verifyDraftText(invalid, titles)); controls++;
}
console.log(`Draft decision bundle: 33 immutable inputs, 20 prerequisite CI receipts, 4 schema-valid/ineligible candidates, 12 target observations, 84 retained metric gaps, 11 blocked gates, 7 pending human decisions and ${controls} rejection controls passed; Draft/not-ready, no selection or sign-off.`);
